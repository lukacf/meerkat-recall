//! Deterministic plain-text rendering and its original UTF-8 byte coordinates.
//! Mapping proves a transform, never source publication or authorization.

use std::ops::Range;

use crate::records::doc_revision::RendererMetadata;

/// Versioned identity shared with the actual default text renderer.
pub const DEFAULT_TEXT_RENDERER_NAME: &str = "elephant.renderer.text";
/// The existing transform is unchanged; mappings describe its original bytes.
pub const DEFAULT_TEXT_RENDERER_VERSION: &str = "1.0.0";

#[derive(Debug, Clone)]
struct Run {
    rendered: Range<usize>,
    original_start: usize,
    // Ordinary copied UTF-8 bytes and lone CR/LF use one original byte per
    // rendered byte. A normalized CRLF uses two. Adjacent runs can coalesce.
    stride: usize,
}

/// Immutable output and the exact origins of its non-generated bytes.
#[derive(Debug, Clone)]
pub struct MappedText {
    text: String,
    runs: Vec<Run>,
}

/// Refusal to use an invalid interval or an unrecognized transform.
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
pub enum MappingError {
    /// The requested rendered interval is empty, reversed, outside the text or
    /// cuts a UTF-8 scalar; intervals are never clipped or repaired.
    #[error("invalid rendered UTF-8 byte interval")]
    InvalidSpan,
    /// The interval contains only text inserted by the renderer.
    #[error("rendered interval has no original source support")]
    GeneratedOnly,
    /// No exact coordinate transform is defined for this renderer/configuration.
    #[error("renderer identity or configuration has no supported source mapping")]
    UnsupportedRenderer,
    /// The complete observed output differs from the pinned transform.
    #[error("immutable rendered text differs from its exact source transform")]
    ChangedOutput,
}

impl MappedText {
    /// Complete immutable rendered output.
    #[must_use]
    pub fn text(&self) -> &str {
        &self.text
    }

    /// Consume the mapping when only rendered output is required.
    #[must_use]
    pub fn into_text(self) -> String {
        self.text
    }

    /// Smallest contiguous original byte cover of this rendered interval.
    /// Removed whitespace between contributing bytes remains in this cover.
    /// Generated terminal LF contributes no original bytes.
    /// # Errors
    /// Refuses invalid UTF-8 intervals and intervals containing only generated text.
    pub fn raw_cover(&self, span: Range<usize>) -> Result<Range<usize>, MappingError> {
        if span.start >= span.end || self.text.get(span.clone()).is_none() {
            return Err(MappingError::InvalidSpan);
        }
        let mut cover: Option<Range<usize>> = None;
        for run in &self.runs {
            let start = span.start.max(run.rendered.start);
            let end = span.end.min(run.rendered.end);
            if start >= end {
                continue;
            }
            let original_start = run.original_start + (start - run.rendered.start) * run.stride;
            let original_end = run.original_start + (end - run.rendered.start) * run.stride;
            match &mut cover {
                Some(cover) => cover.end = original_end,
                None => cover = Some(original_start..original_end),
            }
        }
        cover.ok_or(MappingError::GeneratedOnly)
    }

    fn append_supported(&mut self, text: &str, original_start: usize, stride: usize) {
        if text.is_empty() {
            return;
        }
        let rendered_start = self.text.len();
        self.text.push_str(text);
        if let Some(previous) = self.runs.last_mut() {
            let previous_end = previous.original_start + previous.rendered.len() * previous.stride;
            if previous.rendered.end == rendered_start
                && previous_end == original_start
                && previous.stride == stride
            {
                previous.rendered.end = self.text.len();
                return;
            }
        }
        self.runs.push(Run {
            rendered: rendered_start..self.text.len(),
            original_start,
            stride,
        });
    }

    fn append_line(&mut self, original: &str, content: Range<usize>, ending: Option<Range<usize>>) {
        // Delimiters are ASCII CR/LF, so the ranges constructed by the scanner
        // are exact UTF-8 boundaries. Rust's trim_end is the renderer contract.
        self.append_supported(original[content.clone()].trim_end(), content.start, 1);
        if let Some(ending) = ending {
            self.append_supported("\n", ending.start, ending.len());
        } else {
            self.text.push('\n');
        }
    }
}

/// The existing default text renderer's exact transform, with byte origins.
///
/// CRLF and lone CR become LF, trailing Unicode whitespace is removed from each
/// line, and a final LF is added when the last line has no original terminator.
/// Existing blank lines are retained, including trailing blank lines.
#[must_use]
pub fn normalize_default_text(original: &str) -> MappedText {
    let mut mapped = MappedText {
        text: String::with_capacity(original.len()),
        runs: Vec::new(),
    };
    let bytes = original.as_bytes();
    let mut line_start = 0;
    let mut cursor = 0;
    while cursor < bytes.len() {
        if matches!(bytes[cursor], b'\r' | b'\n') {
            let end = if bytes[cursor] == b'\r' && bytes.get(cursor + 1) == Some(&b'\n') {
                cursor + 2
            } else {
                cursor + 1
            };
            mapped.append_line(original, line_start..cursor, Some(cursor..end));
            cursor = end;
            line_start = end;
        } else {
            cursor += 1;
        }
    }
    if line_start < bytes.len() {
        mapped.append_line(original, line_start..bytes.len(), None);
    } else if bytes.is_empty() {
        // The old empty .lines().join("\n") + "\n" transform also yields LF.
        // The renderer independently rejects an empty document before calling it.
        mapped.text.push('\n');
    }
    mapped
}

/// Map only a known exact renderer over the complete original accepted text.
///
/// Callers must separately verify the accepted source hash, immutable rendered
/// hash, completed publication proof, exact evidence and current authorization.
/// # Errors
/// Refuses unknown identity/configuration, changed full output and invalid or
/// wholly generated intervals. Equal quote bytes elsewhere never select an origin.
pub fn original_text_span(
    original: &str,
    rendered: &str,
    metadata: &RendererMetadata,
    span: Range<usize>,
) -> Result<Range<usize>, MappingError> {
    if metadata.config_hash.is_some() || metadata.version != DEFAULT_TEXT_RENDERER_VERSION {
        return Err(MappingError::UnsupportedRenderer);
    }
    match metadata.name.as_str() {
        DEFAULT_TEXT_RENDERER_NAME => {
            let mapped = normalize_default_text(original);
            if mapped.text() != rendered {
                return Err(MappingError::ChangedOutput);
            }
            mapped.raw_cover(span)
        }
        "elephant.renderer.passthrough" => {
            if original != rendered {
                return Err(MappingError::ChangedOutput);
            }
            if span.start >= span.end || original.get(span.clone()).is_none() {
                return Err(MappingError::InvalidSpan);
            }
            Ok(span)
        }
        _ => Err(MappingError::UnsupportedRenderer),
    }
}

#[cfg(test)]
mod tests {
    #![allow(clippy::unwrap_used, clippy::expect_used)]
    use super::*;

    fn renderer() -> RendererMetadata {
        RendererMetadata {
            name: DEFAULT_TEXT_RENDERER_NAME.into(),
            version: DEFAULT_TEXT_RENDERER_VERSION.into(),
            config_hash: None,
        }
    }

    #[derive(serde::Deserialize)]
    struct LiteralSpan {
        start: usize,
        end: usize,
    }
    #[derive(serde::Deserialize)]
    struct Literal {
        id: String,
        accepted_text: String,
        rendered_text: String,
        raw_span: LiteralSpan,
        raw_quote: String,
        rendered_span: LiteralSpan,
        rendered_quote: String,
    }
    #[derive(serde::Deserialize)]
    struct IndependentFixtures {
        positive_cases: Vec<Literal>,
    }

    #[test]
    fn independent_literal_coordinates_match_without_occurrence_search() {
        // D authored the literal raw/rendered bytes and positions before this
        // implementation. Do not derive expected offsets from the mapper.
        let fixtures: IndependentFixtures = serde_json::from_str(include_str!(
            "../../../tests/recall_preview/render-coordinate-fixtures.json"
        ))
        .unwrap();
        assert_eq!(fixtures.positive_cases.len(), 7);
        for case in fixtures.positive_cases {
            let span = case.rendered_span.start..case.rendered_span.end;
            let mapped = normalize_default_text(&case.accepted_text);
            assert_eq!(mapped.text(), case.rendered_text, "{}", case.id);
            assert_eq!(
                case.rendered_text.get(span.clone()),
                Some(case.rendered_quote.as_str()),
                "{}",
                case.id
            );
            let original =
                original_text_span(&case.accepted_text, &case.rendered_text, &renderer(), span)
                    .unwrap();
            assert_eq!(
                original,
                case.raw_span.start..case.raw_span.end,
                "{}",
                case.id
            );
            assert_eq!(
                case.accepted_text.get(original),
                Some(case.raw_quote.as_str()),
                "{}",
                case.id
            );
        }
    }

    #[test]
    fn passthrough_literal_preserves_utf8_crlf_and_exact_byte_offsets() {
        #[derive(serde::Deserialize)]
        struct PassthroughFixture {
            renderer: RendererMetadata,
            case: Literal,
        }
        let fixture: PassthroughFixture = serde_json::from_str(include_str!(
            "../../../tests/recall_preview_semantics/passthrough-coordinate-fixture.json"
        ))
        .unwrap();
        let case = fixture.case;
        assert_eq!(fixture.renderer.name, "elephant.renderer.passthrough");
        assert_eq!(fixture.renderer.version, "1.0.0");
        assert!(fixture.renderer.config_hash.is_none());
        assert_eq!(
            case.accepted_text.as_bytes(),
            b"A\xc3\xa9\r\n\xe7\x8c\xab\xf0\x9f\x99\x82"
        );
        assert_eq!(case.rendered_text.as_bytes(), case.accepted_text.as_bytes());
        assert!(!case.rendered_text.ends_with('\n'));
        let span = case.rendered_span.start..case.rendered_span.end;
        assert_eq!(
            case.rendered_text.get(span.clone()),
            Some(case.rendered_quote.as_str())
        );
        let original = original_text_span(
            &case.accepted_text,
            &case.rendered_text,
            &fixture.renderer,
            span,
        )
        .unwrap();
        assert_eq!(original, case.raw_span.start..case.raw_span.end);
        assert_eq!(
            case.accepted_text.get(original),
            Some(case.raw_quote.as_str())
        );
        // Literal negative expectations were fixed alongside the fixture.
        for changed in ["Aé\n猫🙂\n", "Aé\r\n猫🙂\n"] {
            assert_eq!(
                original_text_span(&case.accepted_text, changed, &fixture.renderer, 1..12),
                Err(MappingError::ChangedOutput)
            );
        }
        assert_eq!(
            original_text_span(
                &case.accepted_text,
                &case.rendered_text,
                &fixture.renderer,
                2..12
            ),
            Err(MappingError::InvalidSpan)
        );
        let mut alias = fixture.renderer;
        alias.name = "passthrough".into();
        assert_eq!(
            original_text_span(&case.accepted_text, &case.rendered_text, &alias, 1..12),
            Err(MappingError::UnsupportedRenderer)
        );
    }

    #[test]
    fn mapping_refuses_synthetic_intervals_and_changed_transform() {
        let source = "Åsa\r\n🦊.";
        let rendered = "Åsa\n🦊.\n";
        for span in [0..0, std::ops::Range { start: 4, end: 3 }, 6..9, 0..100] {
            assert_eq!(
                original_text_span(source, rendered, &renderer(), span),
                Err(MappingError::InvalidSpan)
            );
        }
        assert_eq!(
            original_text_span("A", "A\n", &renderer(), 1..2),
            Err(MappingError::GeneratedOnly)
        );
        assert_eq!(
            original_text_span("A", "B\n", &renderer(), 0..1),
            Err(MappingError::ChangedOutput)
        );
        for (name, version, config_hash) in [
            ("unknown", "1.0.0", None),
            (DEFAULT_TEXT_RENDERER_NAME, "2", None),
            (DEFAULT_TEXT_RENDERER_NAME, "1.0.0", Some("changed".into())),
        ] {
            let metadata = RendererMetadata {
                name: name.into(),
                version: version.into(),
                config_hash,
            };
            assert_eq!(
                original_text_span("A", "A\n", &metadata, 0..1),
                Err(MappingError::UnsupportedRenderer)
            );
        }
    }

    #[test]
    fn actual_line_terminators_keep_their_original_bytes() {
        for (original, whole, newline) in [
            ("A  \r\n", 0..5, 3..5),
            ("A  \n", 0..4, 3..4),
            ("A  \r", 0..4, 3..4),
        ] {
            let mapped = normalize_default_text(original);
            assert_eq!(mapped.text(), "A\n");
            assert_eq!(mapped.raw_cover(0..2).unwrap(), whole);
            assert_eq!(mapped.raw_cover(1..2).unwrap(), newline);
        }
        let generated = normalize_default_text("A  ");
        assert_eq!(generated.raw_cover(0..2).unwrap(), 0..1);
        assert_eq!(generated.raw_cover(1..2), Err(MappingError::GeneratedOnly));
    }

    #[test]
    fn every_ascii_line_ending_combination_preserves_existing_transform() {
        let parts = ["A", " ", "\t", "\r", "\n", "\u{85}", "🦊"];
        for a in parts {
            for b in parts {
                for c in parts {
                    let original = format!("{a}{b}{c}");
                    let old = original
                        .replace("\r\n", "\n")
                        .replace('\r', "\n")
                        .lines()
                        .map(str::trim_end)
                        .collect::<Vec<_>>()
                        .join("\n")
                        + "\n";
                    assert_eq!(
                        normalize_default_text(&original).text(),
                        old,
                        "{original:?}"
                    );
                }
            }
        }
        assert_eq!(normalize_default_text("").text(), "\n");
        let mapped = normalize_default_text(&"\n".repeat(100_000));
        assert_eq!(
            mapped.runs.len(),
            1,
            "contiguous original newline runs must coalesce"
        );
        assert_eq!(mapped.raw_cover(1..99_999).unwrap(), 1..99_999);
    }
}
